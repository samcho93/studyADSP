<li>개인정보의 3단계 구분: <b>개인정보</b>(식별 가능) · <b>가명정보</b>(추가 정보 없이는 식별 불가) · <b>익명정보</b>(더 이상 식별 불가, 개인정보 보호법 적용 제외).</li>

<h4>2-2. 가설검정의 구성</h4>
<table>
<tr><th>용어</th><th>의미</th></tr>
<tr><td>귀무가설(H0)</td><td>"차이가 없다 · 효과가 없다 · 같다". 검정의 대상이 되는 기본 가설</td></tr>
